"""The forced nomenclature: every instruction is DIRECT or RELATIVE.

This module is the SINGLE SOURCE OF TRUTH for instruction kinds. The
generator draws from these tables, configs are validated against them, and
classify() reads a built instruction back into the same names — so what
was drawn and what is measured can never disagree.

RELATIVE = coupled to another instruction — it takes another instruction's
output as its input, or it changes another instruction's output.
DIRECT   = everything else. Reading DATA is not relative: the live list
(List[0]), its origin (Start), the instruction's own private list (B), and
the positions (Pos) are data, not another instruction's output.

Every direct reference is APPLIER[POSITION]; the direct KIND is the
applier, the direct TYPE is the position form:

    DIRECT      kind          applier            types (position form)
      literal   a plain number                    —
      live      List[…]       the live list      fixed | own | offset | indirect
      origin    Start[…]      the starting list  fixed | own | offset | indirect
      companion B[…]          this line's list   fixed | own | offset | indirect
      positional Pos[…]       the positions      own (p) | fixed (a number)
      composite a mix of the above sources
    RELATIVE
      consumes — uses another instruction's output as input
        effect       Changed[j]
        definition   mirror j, negate j   (j's current meaning)
        execution    unwind j             (j's recorded execution)
      affects — changes another instruction's output
        alter        amplify j, flip j, rewrite j
        erase        cancel j

A data line's APPLICATION (application.py — how it lands on the list) is a
bracketed level: the non-default axes, `direct.live[stride, x3, if]`. An
extent or gate that reads another line (touched j, same as j, Changed[j]
in a gate) makes the whole line relative, exactly as a Changed[j] operand
would. Defaults (whole, map, snapshot, once, always) are never written.

A hold is a TAG ("held"), not a category: it changes when a line runs,
never what it consumes or affects.

Intent: one forced vocabulary so every question, config, and result speaks
the same names — and so instruction-coupling depth ("relative") is measured
separately from data-reading load ("direct").
"""

from collections import Counter
from dataclasses import dataclass

import sympy as sp

from .lines import Instruction, MoveInstruction
from .meta.base import MetaInstruction
from .ops.operands import _CHANGED, POS, START, B, L, P, effect_refs, position_form

CATEGORIES = ("direct", "relative")

# direct kinds: name -> generated by the generator? (composite is never drawn)
DIRECT_KINDS: dict[str, bool] = {
    "literal": True,
    "live": True,
    "origin": True,
    "companion": True,
    "positional": True,
    "move": True,      # a permute line: reverse / rotate / swap / sort
    "composite": False,
}

# relative kinds: name -> (group, verbs). "effect" is a data line with a
# Changed[j] operand, so it has no verb.
RELATIVE_KINDS: dict[str, tuple[str, tuple[str, ...]]] = {
    "effect": ("consumes", ()),
    "definition": ("consumes", ("mirror", "negate")),
    "execution": ("consumes", ("unwind",)),
    "alter": ("affects", ("amplify", "flip", "rewrite")),
    "erase": ("affects", ("cancel",)),
}

VERB_KIND: dict[str, str] = {
    verb: kind for kind, (_, verbs) in RELATIVE_KINDS.items() for verb in verbs
}

_APPLIER_KIND = {L: "live", START: "origin", B: "companion", POS: "positional"}


def check_weights(name: str, weights: dict, allowed) -> None:
    """Reject a weight table whose keys aren't exactly the allowed kinds."""
    allowed = set(allowed)
    got = set(weights)
    if got != allowed:
        raise ValueError(
            f"{name} must weight exactly {sorted(allowed)}; "
            f"unknown {sorted(got - allowed)}, missing {sorted(allowed - got)}"
        )
    if any(w < 0 for w in weights.values()) or sum(weights.values()) <= 0:
        raise ValueError(f"{name} needs non-negative weights with a positive total")


@dataclass(frozen=True)
class Label:
    category: str          # "direct" | "relative"
    group: str | None      # relative only: "consumes" | "affects"
    kind: str              # leaf name (literal, live, ..., effect, alter, ...)
    tags: tuple[str, ...]  # ("held",) when hold_until_after is set
    how: tuple[str, ...] = ()  # the application's non-default axes (data lines)

    def __str__(self) -> str:
        path = (
            f"{self.category}.{self.kind}"
            if self.group is None
            else f"{self.category}.{self.group}.{self.kind}"
        )
        if self.how:
            path += f"[{', '.join(self.how)}]"
        return path + "".join(f"+{t}" for t in self.tags)


def _outer_refs(expr) -> list[sp.Indexed]:
    """References not nested inside another reference's position."""
    refs = expr.atoms(sp.Indexed)
    inner = set()
    for r in refs:
        for idx in r.indices:
            inner |= sp.sympify(idx).atoms(sp.Indexed)
    return [r for r in refs if r not in inner]


def _data_kind(operand) -> tuple[str, str | None, str]:
    expr = sp.sympify(operand)
    refs = expr.atoms(sp.Indexed)
    if any(r.base == _CHANGED for r in refs):
        return "relative", "consumes", "effect"
    sources = {_APPLIER_KIND[r.base] for r in _outer_refs(expr) if r.base in _APPLIER_KIND}
    # bare p (outside any bracket) is Pos[p] by convention
    bare = expr.replace(lambda e: isinstance(e, sp.Indexed), lambda e: sp.Integer(0))
    if bare.has(P):
        sources.add("positional")
    if not sources:
        return "direct", None, "literal"
    if len(sources) == 1:
        return "direct", None, sources.pop()
    return "direct", None, "composite"


def classify(instruction) -> Label:
    tags = ("held",) if instruction.hold_until_after is not None else ()
    if isinstance(instruction, MetaInstruction):
        kind = VERB_KIND[instruction.verb.name]
        return Label("relative", RELATIVE_KINDS[kind][0], kind, tags)
    if isinstance(instruction, Instruction):
        category, group, kind = _data_kind(instruction.operand)
    elif isinstance(instruction, MoveInstruction):
        category, group, kind = "direct", None, "move"
    else:
        raise TypeError(f"unknown instruction kind: {type(instruction).__name__}")
    how = instruction.application
    if how.extent.kind == "same":
        category, group, kind = "relative", "consumes", "definition"
    elif how.extent.kind == "touched" or effect_refs(how.extent.where) or effect_refs(how.gate.where):
        category, group, kind = "relative", "consumes", "effect"
    return Label(category, group, kind, tags, how.marks)


def type_of(instruction) -> str | None:
    """The TYPE beneath the kind: for direct reference kinds the position
    form (fixed | own | offset | indirect); for meta lines the verb; None
    for literals, composites, and effect lines."""
    if isinstance(instruction, MetaInstruction):
        return instruction.verb.name
    if isinstance(instruction, MoveInstruction):
        return instruction.move.name
    label = classify(instruction)
    if label.category != "direct" or label.kind in ("literal", "composite"):
        return None
    expr = sp.sympify(instruction.operand)
    if expr == P:
        return "own"
    outer = _outer_refs(expr)
    return position_form(outer[0].indices[0]) if len(outer) == 1 else None


def mix(instructions) -> dict[str, int]:
    """Realized nomenclature counts for a chain, e.g. {'direct.live': 3, ...}."""
    return dict(Counter(str(classify(ins)) for ins in instructions))


def split(instructions) -> dict[str, int]:
    """Just the top-level split: {'direct': n, 'relative': m}."""
    return dict(Counter(classify(ins).category for ins in instructions))


# ---- R and d: reference depth, MEASURED per question (decision 10) ----
# An edge i -> j wherever line i names line j's result (Changed/Touched in
# an operand, scope or gate; undo of j), definition or scope ("the same
# selection as j"; a meta line's target) — or plants a result reference
# into j (a rewrite's operand). Holds are excluded: they only reorder.
DISTANCES = ("near", "mid", "far")


def distance(i: int, j: int, steps: int) -> str:
    """near: |i − j| <= steps/3 · far: > 2·steps/3 · mid: between."""
    gap = abs(i - j)
    return "near" if 3 * gap <= steps else "far" if 3 * gap > 2 * steps else "mid"


def references(instructions) -> dict[int, set[int]]:
    # dag imports lines/meta; imported here to keep this module light
    from .dag import consumes
    from .ops.operands import scope_refs
    edges: dict[int, set[int]] = {}
    for i, ins in enumerate(instructions, start=1):
        refs = set(consumes(ins))
        if isinstance(ins, MetaInstruction):
            refs.add(ins.target)
            if ins.operand is not None:
                refs |= effect_refs(ins.operand)
        else:
            refs |= scope_refs(ins.application.extent.where)
        edges[i] = {j for j in refs if j != i}
    return edges


def _chain_lengths(edges: dict[int, set[int]]) -> dict[int, int]:
    """For every line, the longest reference chain starting there, in hops."""
    longest: dict[int, int] = {}

    def depth(i: int, path: frozenset) -> int:
        if i in longest:
            return longest[i]
        best = 0
        for j in edges.get(i, ()):
            if j not in path:
                best = max(best, 1 + depth(j, path | {j}))
        longest[i] = best
        return best

    return {i: depth(i, frozenset({i})) for i in edges}


def chain_depths(instructions) -> list[int]:
    """CHAIN DEPTH per line: how many instructions the longest chain that
    starts at that line passes through (itself included) — 1 for a line
    that names no other line. The question's chain depth is the max. A
    measurement for reports, never part of the prompt."""
    hops = _chain_lengths(references(instructions))
    return [1 + hops[i] for i in range(1, len(instructions) + 1)]


def reference_shape(instructions) -> tuple[int, float]:
    """(R, d): R = the longest reference chain, in hops (0 = no coupling);
    d = the share of references that reach FAR. Written `R3 d0.25`."""
    edges = references(instructions)
    steps = len(instructions)
    R = max(_chain_lengths(edges).values(), default=0)
    pairs = [(i, j) for i, js in edges.items() for j in js]
    d = sum(distance(i, j, steps) == "far" for i, j in pairs) / len(pairs) if pairs else 0.0
    return R, round(d, 2)
